func TestAgentTargetAndGeneratedFiles(t *testing.T) {
	f := newCloseFixture(t)
	alphaHandle, alphaID, alphaRoot := createAndOpen(t, "Alpha task", filepath.Join(f.tasks, "alpha"))
	initialRecord := mustRead(t, filepath.Join(f.home, "git", "tasks", alphaID+".md"))
	wantInitialTaskView := "<!-- generated by tt2 from tasks/" + alphaID + ".md; do not edit — use tt2 info / tt2 note -->\n\n" + string(initialRecord)
	if got := string(mustRead(t, filepath.Join(alphaRoot, ".tasktree", "task.md"))); got != wantInitialTaskView {
		t.Fatalf("initial generated task.md mismatch:\n got %q\nwant %q", got, wantInitialTaskView)
	}
	betaOut, _, err := run(t, "new", "Beta task")
	if err != nil {
		t.Fatal(err)
	}
	betaHandle := strings.Fields(betaOut)[0]

	// The environment target works outside a tasktree and takes precedence over
	// the current checkout; -t in turn takes precedence over the environment.
	if err := os.Chdir(f.tasks); err != nil {
		t.Fatal(err)
	}
	t.Setenv("TASKTREE_TASK", betaHandle)
	out, _, err := run(t, "info", "--json")
	if err != nil {
		t.Fatal(err)
	}
	var got record.Task
	if err := json.Unmarshal([]byte(out), &got); err != nil || got.Handle != betaHandle {
		t.Fatalf("env target: task=%+v err=%v", got, err)
	}
	if err := os.Chdir(alphaRoot); err != nil {
		t.Fatal(err)
	}
	out, _, err = run(t, "info", "-t", alphaHandle, "--json")
	if err != nil {
		t.Fatal(err)
	}
	if err := json.Unmarshal([]byte(out), &got); err != nil || got.ID != alphaID {
		t.Fatalf("explicit target: task=%+v err=%v", got, err)
	}
	t.Setenv("TASKTREE_TASK", "missing-task")
	_, _, err = run(t, "info")
	if cli.Code(err) != 3 || !strings.Contains(err.Error(), "TASKTREE_TASK") {
		t.Fatalf("unknown env target code=%d err=%v", cli.Code(err), err)
	}
	t.Setenv("TASKTREE_TASK", betaHandle)

	// Writes made from outside the checkout refresh the generated byte-for-byte
	// copy; it is ignored rather than committed to the task branch.
	if err := os.Chdir(f.tasks); err != nil {
		t.Fatal(err)
	}
	if _, _, err := run(t, "note", "-t", alphaID, "outside note"); err != nil {
		t.Fatal(err)
	}
	recordBytes := mustRead(t, filepath.Join(f.home, "git", "tasks", alphaID+".md"))
	wantTaskView := "<!-- generated by tt2 from tasks/" + alphaID + ".md; do not edit — use tt2 info / tt2 note -->\n\n" + string(recordBytes)
	if gotTaskView := string(mustRead(t, filepath.Join(alphaRoot, ".tasktree", "task.md"))); gotTaskView != wantTaskView {
		t.Fatalf("generated task.md mismatch:\n got %q\nwant %q", gotTaskView, wantTaskView)
	}
	if got := gitRun(t, filepath.Join(f.home, "git"), "ls-tree", "-r", "--name-only", "task/"+alphaID, "--", ".tasktree/task.md"); got != "" {
		t.Fatalf("generated task.md is tracked: %q", got)
	}

	wantAgents := fmt.Sprintf("# Alpha task (%s)\n\nThis folder is a tasktree for task `%s` (id `%s`), managed by `tt2`.\n\n## Rules for agents\n\n- The task record is the source of truth for status, notes, decisions, and references. Read it with `tt2 info` or `.tasktree/task.md` (a generated copy — never edit it).\n- Record progress with `tt2 note \"...\"`; use `--kind decision`, `--kind comment`, or `--kind ref` when it fits. Set `TASKTREE_AUTHOR` to your agent name.\n- Never run git in this folder's root; it is intentionally not a git repository. Record root files and repository commits with `tt2 commit -m \"...\"`.\n- Inside each repository folder, git works normally: branch, commit, push.\n- Add or remove repositories with `tt2 add <alias|url>` and `tt2 remove <name>`. Never `git clone` into this folder.\n- Change task status (`tt2 mark ...`) only when asked.\n\n## Notes\n", alphaHandle, alphaHandle, alphaID)
	if got := gitRun(t, filepath.Join(f.home, "git"), "show", "task/"+alphaID+":AGENTS.md"); got+"\n" != wantAgents {
		t.Fatalf("create commit AGENTS.md mismatch:\n got %q\nwant %q", got+"\n", wantAgents)
	}
	if err := os.Remove(filepath.Join(alphaRoot, "AGENTS.md")); err != nil {
		t.Fatal(err)
	}
	if _, _, err := run(t, "open", alphaID); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(alphaRoot, "AGENTS.md")); !os.IsNotExist(err) {
		t.Fatalf("reopen recreated AGENTS.md: %v", err)
	}

	_, _, err = run(t, "note", "-t", alphaID, "## Log")
	if cli.Code(err) != 2 {
		t.Fatalf("reserved heading note code=%d err=%v", cli.Code(err), err)
	}
	_, _, err = run(t, "note", "-t", alphaID, "### 2026-01-01T00:00:00Z note a@b {#e-abc123}")
	if cli.Code(err) != 2 {
		t.Fatalf("entry header note code=%d err=%v", cli.Code(err), err)
	}
}

func TestF18CrossProcessWritesAndOpens(t *testing.T) {
	base := t.TempDir()
	binary := filepath.Join(base, "tt2")
	repoRoot, err := filepath.Abs(filepath.Join("..", ".."))
	if err != nil {
		t.Fatal(err)
	}
	build := exec.Command("go", "build", "-o", binary, "./cmd/tt2")
	build.Dir = repoRoot
	if output, err := build.CombinedOutput(); err != nil {
		t.Fatalf("build tt2: %v\n%s", err, output)
	}

	homePath, cachePath, tasksPath := filepath.Join(base, "home"), filepath.Join(base, "cache"), filepath.Join(base, "tasks")
	if err := os.MkdirAll(tasksPath, 0o755); err != nil {
		t.Fatal(err)
	}
	env := isolatedEnv(homePath, cachePath, filepath.Join(base, "missing-v1-aliases.yml"))
	runTT2 := func(args ...string) (string, error) {
		cmd := exec.Command(binary, args...)
		cmd.Dir = base
		cmd.Env = env
		out, err := cmd.CombinedOutput()
		if err != nil {
			return string(out), fmt.Errorf("%w: %s", err, out)
		}
		return string(out), nil
	}
	if out, err := runTT2("setup", "--author", "test", "--machine", "box", "--tasks-root", tasksPath); err != nil {
		t.Fatalf("setup: %v\n%s", err, out)
	}
	out, err := runTT2("new", "Concurrent notes")
	if err != nil {
		t.Fatal(err)
	}
	fields := strings.Fields(out)
	if len(fields) != 2 {
		t.Fatalf("new output %q", out)
	}
	noteID := fields[1]

	var wg sync.WaitGroup
	errs := make(chan error, 10)
	for i := 0; i < 10; i++ {
		wg.Add(1)
		go func(i int) {
			defer wg.Done()
			if out, err := runTT2("note", "-t", noteID, fmt.Sprintf("note-%02d", i)); err != nil {
				errs <- fmt.Errorf("note %d: %v\n%s", i, err, out)
			}
		}(i)
	}
	wg.Wait()
	close(errs)
	for err := range errs {
		t.Error(err)
	}
	if t.Failed() {
		return
	}
	doc, err := record.Parse(mustRead(t, filepath.Join(homePath, "git", "tasks", noteID+".md")))
	if err != nil || len(doc.Task.Log) != 10 {
		t.Fatalf("concurrent notes: entries=%d err=%v", len(doc.Task.Log), err)
	}
	if got := gitRun(t, filepath.Join(homePath, "git"), "log", "--format=%s", "--all", "--", "tasks/"+noteID+".md"); strings.Count(got, "task("+noteID+"): note added") != 10 {
		t.Fatalf("note commits=%d log=%q", strings.Count(got, "task("+noteID+"): note added"), got)
	}
	if got := gitRun(t, filepath.Join(homePath, "git"), "status", "--porcelain"); got != "" {
		t.Fatalf("hub dirty after notes: %q", got)
	}

	openIDs := make([]string, 6)
	for i := range openIDs {
		out, err := runTT2("new", fmt.Sprintf("Concurrent open %d", i))
		if err != nil {
			t.Fatal(err)
		}
		openIDs[i] = strings.Fields(out)[1]
	}
	errs = make(chan error, len(openIDs))
	for _, id := range openIDs {
		wg.Add(1)
		go func(id string) {
			defer wg.Done()
			if out, err := runTT2("open", id); err != nil {
				errs <- fmt.Errorf("open %s: %v\n%s", id, err, out)
			}
		}(id)
	}
	wg.Wait()
	close(errs)
	for err := range errs {
		t.Error(err)
	}
	if t.Failed() {
		return
	}
	local, err := (home.Home{Root: homePath}).LoadLocal()
	if err != nil {
		t.Fatal(err)
	}
	for _, id := range openIDs {
		checkout, ok := local.Checkouts[id]
		if !ok {
			t.Errorf("local.yml is missing checkout %s", id)
			continue
		}
		if _, err := os.Stat(checkout.Path); err != nil {
			t.Errorf("checkout %s path %q: %v", id, checkout.Path, err)
		}
	}
}

func isolatedEnv(homePath, cachePath, v1Aliases string) []string {
	keys := map[string]bool{"TASKTREE_HOME": true, "TASKTREE_CACHE_DIR": true, "TASKTREE_V1_ALIASES_FILE": true, "TASKTREE_TASK": true}
	env := make([]string, 0, len(os.Environ())+3)
	for _, item := range os.Environ() {
		key, _, _ := strings.Cut(item, "=")
		if !keys[key] {
			env = append(env, item)
		}
	}
	return append(env, "TASKTREE_HOME="+homePath, "TASKTREE_CACHE_DIR="+cachePath, "TASKTREE_V1_ALIASES_FILE="+v1Aliases)
}
